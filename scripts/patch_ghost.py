'            for (const d of ghostDrums) {\n'
'              const k = (d as unknown as Record<string, unknown>)[key] as string ?? "(없음)";\n'
'              if (!groups[k]) groups[k] = [];\n'
'              groups[k].push(d);\n'
'            }\n'
'            for (const k of Object.keys(groups)) groups[k].sort((a, b) => (a.lot ?? "").localeCompare(b.lot ?? ""));\n'
'            return groups;\n'
'          })();\n'
'\n'
'          const ghostEntries: [string, DrumItem[]][] = ghostSortMode === "섹터별"\n'
'            ? Object.entries(ghostGrouped).sort(([a], [b]) => {\n'
