'                </div>\n'
'              )}\n'
'\n'
'              {ghostDrums.length === 0 ? (\n'
'                <p className="text-sm text-gray-400 text-center py-12">무적 드럼 없음</p>\n'
'              ) : showCardGrid ? (\n'
'                <div>\n'
'                  {(() => {\n'
