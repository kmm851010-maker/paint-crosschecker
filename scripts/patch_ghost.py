'                        {drums.filter(d => selectedLots.has(d.lot)).length > 0 &&\n'
'                          <span className="ml-2 text-purple-600 text-xs">✓{drums.filter(d => selectedLots.has(d.lot)).length}</span>}\n'
'                      </summary>\n'
'                      <div className="p-3 border-t border-gray-100">\n'
'                        {renderGhostDrumTable(drums)}\n'
'                      </div>\n'
'                    </details>\n'
