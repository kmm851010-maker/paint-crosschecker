'                if (ai === -1 && bi === -1) return a.localeCompare(b);\n'
'                if (ai === -1) return 1; if (bi === -1) return -1;\n'
'                return ai - bi;\n'
'              })\n'
'            : Object.entries(ghostGrouped);\n'
'\n'
'          function renderGhostDrumTable(drums: DrumItem[]) {\n'
'            return (\n'
'              <div className="overflow-x-auto rounded border border-gray-200 max-h-[450px] overflow-y-auto">\n'
'                <table className="min-w-full text-sm">\n'
'                  <thead className="bg-gray-50 sticky top-0">\n'
'                    <tr>\n'
'                      <th className="py-2 px-2 text-center w-8">\n'
'                        <input type="checkbox"\n'
'                          checked={drums.length > 0 && drums.every(d => selectedLots.has(d.lot))}\n'
'                          onChange={() => {\n'
'                            const lots = drums.map(d => d.lot);\n'
'                            const allSel = lots.every(l => selectedLots.has(l));\n'
'                            toggleAll(lots, !allSel);\n'
'                          }} />\n'
'                      </th>\n'
'                      <th className="py-2 px-3 text-left text-xs font-semibold text-gray-500">구분</th>\n'
'                      <th className="py-2 px-3 text-left text-xs font-semibold text-gray-500">LOT</th>\n'
