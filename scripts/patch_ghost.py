'        {activeTab === "ghost" && (() => {\n'
'          const ghostDrums = allDrums.filter(d => d.returnStatus?.startsWith("무적"));\n'
'          const ghostSelected = selectedDrums.filter(d => d.returnStatus?.startsWith("무적"));\n'
'\n'
'          const ghostGrouped = (() => {\n'
'            if (ghostSortMode === "등록시간순") {\n'
'              const sorted = [...ghostDrums].sort((a, b) => ((b.registered || "").localeCompare(a.registered || "")));\n'
'              return { "전체 (등록시간순)": sorted };\n'
'            }\n'
'            const key = ghostSortMode === "섹터별" ? "sector" : ghostSortMode === "제조사별" ? "maker" : "product";\n'
